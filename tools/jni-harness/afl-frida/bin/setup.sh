#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
WORK_DIR="${WORK_DIR:-$ROOT_DIR/work}"
SEED_DIR="$WORK_DIR/seeds"
BUILD_DIR="$WORK_DIR/build"
DEVICE_DIR="$WORK_DIR/device"
OUT_DIR="$WORK_DIR/out"
LOG_DIR="$WORK_DIR/logs"
ENV_FILE="$WORK_DIR/env.sh"

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "error: missing required command: $1" >&2
    exit 1
  }
}

require_cmd python3
require_cmd adb

mkdir -p "$SEED_DIR" "$BUILD_DIR" "$DEVICE_DIR" "$OUT_DIR" "$LOG_DIR"

python3 "$SCRIPT_DIR/make_seeds.py" "$SEED_DIR"

cat >"$ENV_FILE" <<EOF
# Generated by tools/jni-harness/afl-frida/bin/setup.sh
export WORK_DIR="$WORK_DIR"
export SEED_DIR="$SEED_DIR"
export BUILD_DIR="$BUILD_DIR"
export DEVICE_DIR="$DEVICE_DIR"
export OUT_DIR="$OUT_DIR"
export LOG_DIR="$LOG_DIR"
export REMOTE_DIR="\${REMOTE_DIR:-/data/local/tmp/flock-afl-frida}"
export TARGET_SO_PATH="\${TARGET_SO_PATH:-}"
export TARGET_SYMBOL="\${TARGET_SYMBOL:-replace_me}"
export TARGET_CALL_MODE="\${TARGET_CALL_MODE:-image_frame}"
export FRIDA_VERSION_PIN="\${FRIDA_VERSION_PIN:-16.1.4}"
export AFL_TIMEOUT="\${AFL_TIMEOUT:-1000}"
export AFLPP_ROOT="\${AFLPP_ROOT:-}"
export ANDROID_NDK_ROOT="\${ANDROID_NDK_ROOT:-\${ANDROID_NDK_HOME:-}}"
EOF

echo "workspace ready: $WORK_DIR"
echo "seed corpus:      $SEED_DIR"
echo "build output:     $BUILD_DIR"
echo "device staging:   $DEVICE_DIR"
echo "AFL++ output:     $OUT_DIR"
echo "env file:         $ENV_FILE"
echo "next: set TARGET_SO_PATH, TARGET_SYMBOL, and ANDROID_NDK_ROOT, then run bin/build-harness.sh"
